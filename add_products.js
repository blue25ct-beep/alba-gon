while (i < lines.length) {
    if (lines[i].match(/^\\d+$/) && lines[i+1] === '-' && lines[i+2].match(/^\\d+$/)) {
        // We found a block of attributes.
        // It means lines[i-1] is the product name
        const name = lines[i-1];
        const minOrderQty = parseInt(lines[i+2], 10) || 1; // 4th value
        const costStr = lines[i+4];
        let cost = parseInt(costStr.replace(/,/g, ''), 10) || 0;
        const barcode = lines[i+8]; // 10th value

        if (barcode && barcode.match(/^\\d+$/)) {
            items.push({
                barcode,
                name,
                price: cost,
                cost: cost,
                category: '주류',
                targetStock: minOrderQty * 1, // e.g., 20
                minOrderQty: minOrderQty
            });
        }
        
        i += 11; // Skip the block
    } else {
        i++;
    }
}

